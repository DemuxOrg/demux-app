"""SQLAlchemy declarative base and shared column mixins.

Responsible for:
- `Base`: the DeclarativeBase every model inherits from (Alembic reads its metadata).
- `IdMixin`: UUID primary key generated by the database (`gen_random_uuid()`).
- `TimestampMixin`: timezone-aware UTC `created_at` / `updated_at`.

New models should inherit `Base, IdMixin, TimestampMixin`.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, func, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    pass


class IdMixin:
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )


class TimestampMixin:
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )
